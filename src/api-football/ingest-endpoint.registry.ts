export function bundleFieldsForIntelHash(): string[] {
  return AF_INGEST_ENDPOINT_REGISTRY.filter((e) => e.hashInIntelContent)
    .flatMap((e) => e.storageKeys)
    .filter((k) => k.startsWith('MatchAfRawBundle.'))
    .map((k) => k.replace('MatchAfRawBundle.', ''));
}
