/** Match-scoped endpoints shown in per-match coverage UI */
export function registryMatchScopedForCoverage(): AfIngestEndpointDefinition[] {
  return AF_INGEST_ENDPOINT_REGISTRY.filter((e) => e.scope === 'match');
}

export function registryRequiredForWorldCup(): AfIngestEndpointDefinition[] {
  return AF_INGEST_ENDPOINT_REGISTRY.filter((e) => e.requiredForWorldCup);
}

export function registryById(id: string): AfIngestEndpointDefinition | undefined {
  return AF_INGEST_ENDPOINT_REGISTRY.find((e) => e.id === id);
}

